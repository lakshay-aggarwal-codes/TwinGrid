"""Task 8: the carbon signal loads once, the fallback warning is logged once, and a user-supplied series is validated.

All data here is generated by the tests in tmp_path for schema checks. It is synthetic test input, not carbon data.
"""

from __future__ import annotations

import json
import logging
from datetime import datetime, timedelta, timezone

import numpy as np
import pandas as pd
import pytest

from src import carbon_ingest as ci
from src import carbon_provider as cp
from src.digital_twin import DigitalTwin

META = {
    "semantic": "average",
    "unit": "gCO2/kWh",
    "source": "synthetic test fixture",
    "license_ref": "test-only",
    "retrieved_at": "2026-10-01T00:00:00Z",
}


@pytest.fixture(autouse=True)
def _fresh_cache():
    cp.clear_carbon_cache()
    yield
    cp.clear_carbon_cache()


def _rows(hours: int = 48, start=datetime(2026, 1, 1, tzinfo=timezone.utc), zone="Z1", base=300.0):
    return [
        {
            "timestamp_utc": (start + timedelta(hours=h)).strftime("%Y-%m-%dT%H:%M:%SZ"),
            "carbon_intensity_gco2_per_kwh": base + (h % 24),
            "zone": zone,
        }
        for h in range(hours)
    ]


def _csv(tmp_path, rows, name="in.csv"):
    p = tmp_path / name
    pd.DataFrame(rows).to_csv(p, index=False)
    return p


def _missing_warnings(caplog):
    return [r for r in caplog.records if "not found" in r.getMessage() and "flat assumed" in r.getMessage()]


# ----------------------------------------------------------------------------- (a) load once, warn once


def test_the_fallback_warning_is_logged_once_not_once_per_twin(tmp_path, monkeypatch, caplog):
    monkeypatch.setattr(cp, "CLEANED_CARBON_PATH", tmp_path / "absent.csv")
    with caplog.at_level(logging.WARNING, logger="src.carbon_provider"):
        for _ in range(25):
            assert DigitalTwin().carbon_data_is_real is False
    assert len(_missing_warnings(caplog)) == 1


def test_a_missing_file_is_loaded_once(tmp_path, monkeypatch):
    monkeypatch.setattr(cp, "CLEANED_CARBON_PATH", tmp_path / "absent.csv")
    calls = []
    real = cp._load_carbon_signal_uncached
    monkeypatch.setattr(cp, "_load_carbon_signal_uncached", lambda *a, **k: calls.append(1) or real(*a, **k))
    for _ in range(10):
        cp.load_carbon_signal()
        cp.load_diurnal_carbon_intensity()
    assert len(calls) == 1


def test_a_file_that_appears_later_is_read_not_shadowed_by_the_cached_fallback(tmp_path, monkeypatch):
    target = tmp_path / "carbon_intensity.csv"
    monkeypatch.setattr(cp, "CLEANED_CARBON_PATH", target)
    assert cp.load_carbon_signal().is_fallback is True
    _csv(tmp_path, _rows(), "carbon_intensity.csv")
    sig = cp.load_carbon_signal()
    assert sig.is_fallback is False and cp.load_diurnal_carbon_intensity()[1] is True
    target.unlink()
    assert cp.load_carbon_signal().is_fallback is True  # and back again


def test_clearing_the_cache_allows_one_more_warning(tmp_path, monkeypatch, caplog):
    monkeypatch.setattr(cp, "CLEANED_CARBON_PATH", tmp_path / "absent.csv")
    with caplog.at_level(logging.WARNING, logger="src.carbon_provider"):
        cp.load_carbon_signal()
        cp.clear_carbon_cache()
        cp.load_carbon_signal()
    assert len(_missing_warnings(caplog)) == 2


def test_other_zones_or_paths_each_warn_once(tmp_path, monkeypatch, caplog):
    monkeypatch.setattr(cp, "CLEANED_CARBON_PATH", tmp_path / "absent.csv")
    with caplog.at_level(logging.WARNING, logger="src.carbon_provider"):
        for _ in range(3):
            cp.load_carbon_signal("A")
            cp.load_carbon_signal("B")
    assert len(_missing_warnings(caplog)) == 2


def test_caching_does_not_change_the_numbers(tmp_path, monkeypatch):
    monkeypatch.setattr(cp, "CLEANED_CARBON_PATH", tmp_path / "absent.csv")
    cached = cp.load_diurnal_carbon_intensity()[0]
    cp.clear_carbon_cache()
    fresh = cp._load_carbon_signal_uncached().curve_by_site_local_hour
    assert np.array_equal(cached, fresh) and np.all(cached == cp.FALLBACK_FLAT_INTENSITY_GCO2_PER_KWH)
    # a cached curve is a copy: mutating it cannot corrupt the next caller's
    cached[:] = 0.0
    assert np.all(cp.load_diurnal_carbon_intensity()[0] == cp.FALLBACK_FLAT_INTENSITY_GCO2_PER_KWH)


def test_a_fixed_seed_episode_is_identical_with_and_without_the_cache(tmp_path, monkeypatch):
    from src.optimizer import DataCentreEnv

    monkeypatch.setattr(cp, "CLEANED_CARBON_PATH", tmp_path / "absent.csv")

    def episode(clear_each_time: bool):
        if clear_each_time:
            cp.clear_carbon_cache()
        env = DataCentreEnv(physics_version="1", seed=3, max_steps=12)
        env.reset(seed=3)
        out = []
        for _ in range(12):
            _o, reward, term, trunc, info = env.step(np.array([0.5, 0.5], dtype=np.float32))
            out.append((float(reward), info.get("outlet_temp_C", None)))
            if term or trunc:
                break
        return out

    assert episode(True) == episode(False)


# ----------------------------------------------------------------------------- (b) ingestion: schema validation


def test_a_valid_series_passes_and_reports_what_it_found(tmp_path):
    rep = ci.validate_carbon_csv(_csv(tmp_path, _rows()), META)
    assert rep.ok and rep.errors == [] and rep.rows == 48 and rep.zones == ["Z1"]
    assert rep.resolution_s == 3600 and rep.missing_site_local_hours == [] and len(rep.csv_sha256) == 64


@pytest.mark.parametrize(
    ("mutate", "needle"),
    [
        (lambda r: [{**x, "timestamp_utc": x["timestamp_utc"][:-1]} for x in r], "no explicit offset"),  # naive
        (
            lambda r: [{**x, "carbon_intensity_gco2_per_kwh": -1} if i == 3 else x for i, x in enumerate(r)],
            "outside 0..",
        ),
        (
            lambda r: [{**x, "carbon_intensity_gco2_per_kwh": 475000} if i == 3 else x for i, x in enumerate(r)],
            "unit error",
        ),
        (
            lambda r: [{**x, "carbon_intensity_gco2_per_kwh": "n/a"} if i == 3 else x for i, x in enumerate(r)],
            "not a number",
        ),
        (
            lambda r: [{**x, "carbon_intensity_gco2_per_kwh": "nan"} if i == 3 else x for i, x in enumerate(r)],
            "outside 0..",
        ),
        (lambda r: [{**x, "zone": ""} if i == 3 else x for i, x in enumerate(r)], "empty zone"),
        (lambda r: r + [r[-1]], "duplicate timestamp"),
        (lambda r: [r[1], r[0], *r[2:]], "not increasing"),
        (lambda r: r[:10] + r[20:], "gap"),
        (lambda r: [], "no data rows"),
    ],
)
def test_bad_series_are_refused_with_a_reason(tmp_path, mutate, needle):
    rep = ci.validate_carbon_csv(_csv(tmp_path, mutate(_rows())) if mutate(_rows()) else _empty(tmp_path), META)
    assert rep.ok is False and any(needle in e for e in rep.errors), rep.errors


def _empty(tmp_path):
    p = tmp_path / "empty.csv"
    p.write_text("timestamp_utc,carbon_intensity_gco2_per_kwh,zone\n", encoding="utf-8")
    return p


def test_a_missing_column_is_refused(tmp_path):
    p = _csv(tmp_path, [{k: v for k, v in r.items() if k != "zone"} for r in _rows()])
    rep = ci.validate_carbon_csv(p, META)
    assert not rep.ok and "missing column(s): zone" in rep.errors[0]


def test_a_missing_file_is_refused(tmp_path):
    assert ci.validate_carbon_csv(tmp_path / "nope.csv", META).ok is False


@pytest.mark.parametrize(
    ("patch", "needle"),
    [
        ({"semantic": "marginal-ish"}, "semantic"),
        ({"semantic": None}, "semantic is required"),
        ({"unit": "lb/MWh"}, "unit must be exactly"),
        ({"source": ""}, "source is required"),
        ({"license_ref": None}, "license_ref is required"),
        ({"retrieved_at": "2026-10-01"}, "retrieved_at"),
        ({"retrieved_at": "2026-10-01T00:00:00"}, "retrieved_at"),
        ({"resolution_s": -5}, "resolution_s"),
    ],
)
def test_incomplete_or_wrong_provenance_is_refused(tmp_path, patch, needle):
    meta = {**META, **patch}
    meta = {k: v for k, v in meta.items() if v is not None}
    rep = ci.validate_carbon_csv(_csv(tmp_path, _rows()), meta)
    assert not rep.ok and any(needle in e for e in rep.errors), rep.errors


def test_provenance_must_be_an_object(tmp_path):
    assert ci.validate_carbon_csv(_csv(tmp_path, _rows()), ["x"]).ok is False


def test_partial_hour_coverage_is_refused_unless_allowed_and_then_is_still_a_fallback(tmp_path, monkeypatch):
    rows = [r for r in _rows(48) if int(r["timestamp_utc"][11:13]) < 12]  # UTC 00..11 only
    path = _csv(tmp_path, rows)
    strict = ci.validate_carbon_csv(path, META)
    assert not strict.ok and strict.missing_site_local_hours and any("is_fallback=True" in e for e in strict.errors)
    lenient = ci.validate_carbon_csv(path, META, allow_partial_hours=True, max_gap_factor=100)
    assert lenient.ok and lenient.warnings
    target = tmp_path / "out" / "carbon_intensity.csv"
    monkeypatch.setattr(cp, "CLEANED_CARBON_PATH", target)
    ci.install_carbon_csv(
        path, {**META, "resolution_s": 3600}, target=target, allow_partial_hours=True, max_gap_factor=100
    )
    assert cp.load_carbon_signal().is_fallback is True and DigitalTwin().carbon_data_is_real is False


# ----------------------------------------------------------------------------- (b)+(c) install and the is_real flag


def test_install_writes_the_provenance_sidecar_and_the_loader_reports_real(tmp_path, monkeypatch):
    target = tmp_path / "data" / "cleaned" / "carbon_intensity.csv"
    monkeypatch.setattr(cp, "CLEANED_CARBON_PATH", target)
    assert DigitalTwin().carbon_data_is_real is False  # before: the labelled fallback
    src = _csv(tmp_path, _rows())
    ci.install_carbon_csv(src, META, target=target)
    side = json.loads(target.with_name(cp.CARBON_META_FILENAME).read_text(encoding="utf-8"))
    assert side["semantic"] == "average" and side["license_ref"] == "test-only" and side["rows"] == 48
    assert side["csv_sha256"] == ci._sha256(src) and side["unit"] == "gCO2/kWh"
    sig = cp.load_carbon_signal()
    basis = sig.basis()
    assert (sig.is_fallback, sig.semantic, sig.license_ref) == (False, "average", "test-only")
    assert basis["is_fallback"] is False and basis["time_varying_signal"] is True
    assert DigitalTwin().carbon_data_is_real is True


def test_install_refuses_an_invalid_file_and_touches_nothing(tmp_path):
    target = tmp_path / "out" / "carbon_intensity.csv"
    bad = _csv(tmp_path, [{**r, "carbon_intensity_gco2_per_kwh": -5} for r in _rows()])
    with pytest.raises(ValueError, match="refused"):
        ci.install_carbon_csv(bad, META, target=target)
    assert not target.exists() and not target.parent.exists()


def test_install_does_not_overwrite_without_the_flag(tmp_path):
    target = tmp_path / "carbon_intensity.csv"
    src = _csv(tmp_path, _rows())
    ci.install_carbon_csv(src, META, target=target)
    with pytest.raises(FileExistsError):
        ci.install_carbon_csv(src, META, target=target)
    ci.install_carbon_csv(src, META, target=target, overwrite=True)


def test_cli_validate_exit_codes(tmp_path, capsys):
    good = _csv(tmp_path, _rows())
    meta = tmp_path / "m.json"
    meta.write_text(json.dumps(META), encoding="utf-8")
    assert ci.main(["validate", "--csv", str(good), "--meta", str(meta)]) == 0
    meta.write_text(json.dumps({**META, "unit": "kg/MWh"}), encoding="utf-8")
