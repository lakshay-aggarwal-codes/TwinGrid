"""Synthetic telemetry for testing the calibration PIPELINE (parameter recovery). Always labelled synthetic.

Output of this module is never measured data, and a result computed from it never carries the word
"calibrated" (see ``fit.calibrate``).
"""

from __future__ import annotations

import numpy as np

from src.physics.params import PhysicsParams

from .data import INPUT_CHANNELS, OUTPUT_CHANNELS, CalibrationData
from .fit import Segment, simulate


def synthetic_dataset(
    truth: PhysicsParams, *, days: int = 6, cadence_s: float = 300.0, seed: int = 0, mode: str = "closed_loop"
) -> CalibrationData:
    rng = np.random.default_rng(seed)
    per_day = int(86400 / cadence_s)
    n = days * per_day
    t = np.arange(n) * cadence_s / 3600.0
    hold = max(1, int(3600 / cadence_s))  # the load changes about hourly: the steps that excite the room dynamics
    steps = rng.uniform(0.2, 0.9, size=n // hold + 1)
    util = np.clip(np.repeat(steps, hold)[:n] * (0.85 + 0.15 * np.sin(2 * np.pi * t / 24.0)), 0.0, 1.0)
    temp = 20.0 + 8.0 * np.sin(2 * np.pi * (t - 9.0) / 24.0) + rng.normal(0, 0.3, n)
    hum = np.clip(55.0 + 15.0 * np.sin(2 * np.pi * (t + 3.0) / 24.0) + rng.normal(0, 2.0, n), 5.0, 95.0)
    chw_steps = rng.uniform(8.0, 14.0, size=n // (3 * hold) + 1)
    chw = np.repeat(chw_steps, 3 * hold)[:n]

    seg = Segment(0, util, temp, hum, chw, [mode] * n, {})
    sim = simulate(truth, seg, cadence_s)
    noise = {"it_power_kw": 0.01, "t_in_c": 0.1, "t_out_c": 0.1, "cooling_power_kw": 0.01}
    values: dict[str, np.ndarray] = {
        "utilisation": util,
        "outside_temp_c": temp,
        "humidity_pct": hum,
        "chw_requested_c": chw,
    }
    for ch in OUTPUT_CHANNELS:
        scale = noise[ch] * (sim[ch] if ch.endswith("_kw") else 1.0)
        values[ch] = sim[ch] + rng.normal(0.0, 1.0, n) * (np.abs(scale) if ch.endswith("_kw") else noise[ch])
    ts = np.datetime64("2026-01-05T00:00:00") + (np.arange(n) * int(cadence_s)).astype("timedelta64[s]")
    return CalibrationData(
        dataset_id=f"SYNTHETIC-seed{seed}",
        ts=ts,
        cadence_s=cadence_s,
        values={ch: values[ch] for ch in INPUT_CHANNELS + OUTPUT_CHANNELS},
        observed={ch: np.ones(n, dtype=bool) for ch in INPUT_CHANNELS + OUTPUT_CHANNELS},
        mode=np.array([mode] * n, dtype=object),
        synthetic=True,
        report={"note": "synthetic; generated by src/calibration/synthetic.py"},
    )
