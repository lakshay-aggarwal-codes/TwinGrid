"""Task 18: the Model Passport. PURE builder over ``models/registry.json`` entries, the detector config and the stored
evaluation decision. It reads nothing itself and invents nothing: every field is either copied from its source or
derived by a rule written here, and the static wording is quoted from ``docs/model_cards/`` (a test pins each phrase to
the card it comes from).

Honesty rules:
* every model in this system was trained on simulator-generated data (``docs/model_cards/LIMITATIONS.md``), so every
  metric is labelled a synthetic-data result and ``data_origin`` is ``synthetic``;
* a number the registry does not hold is ``None``, never a default; PPO state is explained from the stored decision
  (for example ``NOT_EVALUATED``) and from the registry status, never implied;
* ``loadable`` only says the registry status allows the API to load it (``promoted``); it does not say the integrity
  check passed.
"""

from __future__ import annotations

import math
from typing import Any, Mapping, Sequence

SCHEMA_VERSION = 1
METRICS_LABEL = "synthetic-data result"
SHARED_LIMITATION = (
    "Metrics (F1, RMSE, PUE improvement) measure how well each model fits the simulator's own physics/patterns, "
    "not real-world generalization."
)
SHARED_BOUNDARY = (
    'Report these metrics as "performance on the current simulator," not as a claim about real-facility performance'
)

#: kind -> (source card, limitation phrases quoted from it)
KIND_LIMITATIONS: dict[str, tuple[str, tuple[str, ...]]] = {
    "anomaly": (
        "docs/model_cards/anomaly_detector.md",
        (
            "Synthetic training data",
            "this is not SHAP; it's a cheaper, dependency-free proxy specific to autoencoders",
            "precision is inherently capped low relative to a balanced-class problem",
        ),
    ),
    "forecaster": (
        "docs/model_cards/forecaster.md",
        (
            "Trained entirely on synthetic data generated by the same physics model the rest of the system uses",
            "No held-out *drought* scenario in the forecaster's own training/eval split specifically",
        ),
    ),
    "ppo": (
        "docs/model_cards/ppo_optimizer.md",
        (
            "3 seeds is a minimum, not a statistically strong sample",
            "No adversarial/out-of-distribution testing",
            "Trained against the live `DigitalTwin` simulation directly, not historical facility data",
        ),
    ),
}

EXPLANATION_METHOD = {
    "anomaly": "Reconstruction-error shares per input feature while an episode is live (src/anomaly_explain.py), plus a deterministic range deviation of the stored reading. Not SHAP.",
}

_NO_EVAL = "No evaluation report is stored, so no claim about this policy's quality can be made."


def _finite(v: Any) -> bool:
    return isinstance(v, (int, float)) and not isinstance(v, bool) and math.isfinite(v)


def headline_metrics(metrics: Any) -> list[dict[str, Any]]:
    """Top-level finite numbers of the registry ``metrics`` object, in registry order. Nested objects are not flattened."""
    if not isinstance(metrics, Mapping):
        return []
    return [{"name": str(k), "value": float(v)} for k, v in metrics.items() if _finite(v)]


def _str(v: Any) -> str | None:
    return v if isinstance(v, str) and v.strip() else None


def _claim_boundary(entry: Mapping[str, Any]) -> str:
    metrics = entry.get("metrics")
    stated = _str(metrics.get("claim")) if isinstance(metrics, Mapping) else None
    status = entry.get("status")
    if status == "quarantined":
        reason = _str(entry.get("status_reason"))
        return f"Quarantined: the API does not load it.{' ' + reason if reason else ''} {SHARED_BOUNDARY}."
    if stated:
        return f"{stated}. {SHARED_BOUNDARY}."
    return f"{SHARED_BOUNDARY}."


def evaluation_state(entry: Mapping[str, Any], decision: Mapping[str, Any] | None) -> dict[str, Any] | None:
    """PPO only. What the STORED decision says, verbatim; None for other kinds."""
    if entry.get("kind") != "ppo":
        return None
    metrics = entry.get("metrics")
    nulls = metrics.get("null_reasons") if isinstance(metrics, Mapping) else None
    entry_reason = _str(nulls.get("evaluation_ref")) if isinstance(nulls, Mapping) else None
    if decision is None:
        return {
            "outcome": "NOT_EVALUATED",
            "claim_allowed": "none",
            "reason": entry_reason or _NO_EVAL,
            "source": "registry (no evaluation report stored)",
            "evaluation_id": None,
        }
    return {
        "outcome": _str(decision.get("outcome")) or "NOT_EVALUATED",
        "claim_allowed": _str(decision.get("claim_allowed")) or "none",
        "reason": _str(decision.get("reason")) or entry_reason,
        "source": "latest stored evaluation report",
        "evaluation_id": _str(decision.get("evaluation_id")),
    }


def build_passport_entry(
    entry: Mapping[str, Any], *, decision: Mapping[str, Any] | None, detector: Mapping[str, Any] | None
) -> dict[str, Any]:
    kind = _str(entry.get("kind")) or "unknown"
    card, limitations = KIND_LIMITATIONS.get(kind, (None, ()))
    status = _str(entry.get("status")) or "unknown"
    out: dict[str, Any] = {
        "model_id": _str(entry.get("model_id")) or "",
        "name": _str(entry.get("name")),
        "kind": kind,
        "version": _str(entry.get("version")),
        "status": status,
        "status_reason": _str(entry.get("status_reason")),
        "loadable": status == "promoted",
        "created_at_utc": _str(entry.get("created_at_utc")),
        "data_origin": "synthetic",
        "data_origin_basis": "docs/model_cards/LIMITATIONS.md: every model here is trained on simulator-generated data, not measurements from a real facility",
        "data_source": _str(entry.get("data_source")),
        "dataset_id": _str(entry.get("dataset_id")),
        "physics_version": _str(entry.get("physics_version")),
        "metrics_label": METRICS_LABEL,
        "headline_metrics": headline_metrics(entry.get("metrics")),
        "limitations": [SHARED_LIMITATION, *limitations],
        "limitations_source": ["docs/model_cards/LIMITATIONS.md", *([card] if card else [])],
        "claim_boundary": _claim_boundary(entry),
        "evaluation": evaluation_state(entry, decision),
    }
    if kind == "anomaly":
        out["explanation_method"] = EXPLANATION_METHOD["anomaly"]
        out["detector"] = dict(detector) if detector else None
    return out


def build_passport(
    entries: Sequence[Mapping[str, Any]],
    *,
    decision: Mapping[str, Any] | None,
    detector: Mapping[str, Any] | None,
) -> dict[str, Any]:
    """The ``GET /api/models/passport`` body. Registry order is kept (oldest first); nothing is dropped or ranked."""
    return {
        "schema_version": SCHEMA_VERSION,
        "origin": "registry",
        "metrics_label": METRICS_LABEL,
        "sources": ["models/registry.json", "models/anomaly/config.json", "reports/policy_evaluation/"],
        "models": [build_passport_entry(e, decision=decision, detector=detector) for e in entries],
    }
