<#
 One-command demo (Windows PowerShell 5.1+ / PowerShell 7). Run from anywhere:  .\scripts\demo.ps1
 Needs Docker Desktop. Optional: -WithFrontend also installs and starts the frontend dev server on :8080 (needs Node).
 Everything shown is SIMULATED data. Not for a real deployment (it runs the API with ENVIRONMENT=development).

 Steps: create .env.demo once (random infrastructure secrets, git-ignored) -> start db, redis and the API
 (migrations run on start) -> seed (scripts/demo_seed.py, DEMO_MODE=true) -> print URLs and the demo logins.
 The three demo passwords are generated by the seed, printed ONCE below and kept nowhere else.
 Reset to a fresh demo:  docker compose --env-file .env.demo -f docker-compose.yml -f docker-compose.demo.yml down -v
#>
param([switch]$WithFrontend)
$ErrorActionPreference = 'Stop'
Set-Location (Split-Path -Parent $PSScriptRoot)

function New-Secret([int]$Length) {
  $chars = [char[]]'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789'
  $bytes = New-Object byte[] $Length
  $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
  try { $rng.GetBytes($bytes) } finally { $rng.Dispose() }
  -join ($bytes | ForEach-Object { $chars[$_ % $chars.Length] })
}

$envFile = '.env.demo'
if (-not (Test-Path $envFile)) {
  # Infrastructure secrets only (database, cache, token signing). The demo USER passwords are not stored here.
  $lines = @(
    "POSTGRES_PASSWORD=$(New-Secret 32)",
    "REDIS_PASSWORD=$(New-Secret 32)",
    "JWT_SECRET_KEY=$(New-Secret 64)"
  )
  [System.IO.File]::WriteAllLines((Join-Path (Get-Location) $envFile), $lines)
  Write-Host "Created $envFile (random local secrets; git-ignored)."
}

$compose = @('compose', '--env-file', $envFile, '-f', 'docker-compose.yml', '-f', 'docker-compose.demo.yml')

Write-Host 'Starting database, cache and API (first run builds the image and can take several minutes)...'
& docker @compose up -d --build --wait db redis backend
if ($LASTEXITCODE -ne 0) { throw 'docker compose up failed' }

Write-Host 'Seeding simulated demo data...'
& docker @compose run --rm demo-seed
if ($LASTEXITCODE -ne 0) { throw 'demo seed failed' }

Write-Host ''
Write-Host 'API:       http://localhost:8000   (health: http://localhost:8000/healthz)'
Write-Host 'Frontend:  http://localhost:8080   (start it with: cd twin-stream-insight-main; npm ci; npm run dev)'
Write-Host 'Sign in with one of the demo logins printed above (viewer / operator / admin). All data is simulated.'

if ($WithFrontend) {
  Set-Location twin-stream-insight-main
  & npm ci
  if ($LASTEXITCODE -ne 0) { throw 'npm ci failed' }
  & npm run dev
}
